def _force_rgb_transform():
    """Ensures PIL images are converted to 3-channel RGB before model-specific transforms."""
    return transforms.Lambda(lambda img: img.convert("RGB"))

def _make_loaders_from_transform(
    tfm, data_root: str, batch_size: int, workers: int
) -> Tuple[DataLoader, DataLoader, DataLoader]:
    # Use 'validation' if it exists, otherwise try 'val'
    val_folder = "validation" if os.path.exists(os.path.join(data_root, "validation")) else "val"
    if not os.path.exists(os.path.join(data_root, val_folder)):
         raise FileNotFoundError(f"Neither 'validation' nor 'val' directory found under {data_root}")

    train_dir = os.path.join(data_root, "train")
    val_dir   = os.path.join(data_root, val_folder)
    test_dir  = os.path.join(data_root, "test")

    if not os.path.exists(train_dir): raise FileNotFoundError(f"Train directory not found: {train_dir}")
    if not os.path.exists(val_dir):   raise FileNotFoundError(f"Validation directory not found: {val_dir}")
    if not os.path.exists(test_dir):  raise FileNotFoundError(f"Test directory not found: {test_dir}")


    train_ds = datasets.ImageFolder(train_dir,
                                    transform=transforms.Compose([_force_rgb_transform(), tfm]))
    val_ds   = datasets.ImageFolder(val_dir,
                                    transform=transforms.Compose([_force_rgb_transform(), tfm]))
    test_ds  = datasets.ImageFolder(test_dir,
                                    transform=transforms.Compose([_force_rgb_transform(), tfm]))

    # Only use persistent_workers if num_workers > 0
    pw = PERSISTENT if workers > 0 else False

    train_loader = DataLoader(train_ds, batch_size=batch_size, shuffle=True,
                              num_workers=workers, pin_memory=PIN_MEMORY, persistent_workers=pw)
    val_loader   = DataLoader(val_ds, batch_size=batch_size, shuffle=False,
                              num_workers=workers, pin_memory=PIN_MEMORY, persistent_workers=pw)
    test_loader  = DataLoader(test_ds, batch_size=batch_size, shuffle=False,
                              num_workers=workers, pin_memory=PIN_MEMORY, persistent_workers=pw)
    return train_loader, val_loader, test_loader

