def compute_class_weights(ds, num_classes):
    counts = Counter()
    total = 0
    for _, y in ds.unbatch():
        yi = int(y.numpy())
        counts[yi] += 1
        total += 1
    class_weights = {}
    for c in range(num_classes):
        # inverse frequency weighting
        class_weights[c] = total / (num_classes * max(1, counts.get(c, 1)))
    return class_weights

CLASS_WEIGHTS = compute_class_weights(train_ds, NUM_CLASSES)

# --------------------------------------------------------------------------------
# 1) Model: Augment -> preprocess_input -> ResNet50V2 -> GAP -> Dropout -> Dense
# --------------------------------------------------------------------------------
from tensorflow.keras import layers as L
from tensorflow.keras.applications import ResNet50V2
from tensorflow.keras.applications.resnet_v2 import preprocess_input

# Get input shape from a single batch to be safe
for xb, _ in train_ds.take(1):
    H, W, C = xb.shape[1], xb.shape[2], xb.shape[3]
input_shape = (H, W, C)

data_augment = tf.keras.Sequential([
    L.RandomFlip("horizontal"),
    L.RandomRotation(0.05),
    L.RandomZoom(0.1),
    L.RandomContrast(0.1),
], name="augment")

inputs = L.Input(shape=input_shape)
x = data_augment(inputs)
x = L.Lambda(preprocess_input, name="resnetv2_preprocess")(x)

base_model = ResNet50V2(include_top=False, weights="imagenet", input_tensor=x)
base_model.trainable = False  # warm-up with backbone frozen

x = L.GlobalAveragePooling2D(name="gap")(base_model.output)
x = L.Dropout(0.35)(x)
outputs = L.Dense(NUM_CLASSES, activation="softmax", name="classifier")(x)

model = tf.keras.Model(inputs=inputs, outputs=outputs, name="ResNet50V2_FER")

# --------------------------------------------------------------------------------
# 2) Warm-up: train top head only
# --------------------------------------------------------------------------------
model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=3e-3),
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

warmup_cbs = [
    tf.keras.callbacks.ReduceLROnPlateau(
        monitor="val_loss", factor=0.5, patience=2, min_lr=1e-5, verbose=1
    ),
    tf.keras.callbacks.EarlyStopping(
        monitor="val_accuracy", mode="max", patience=5, restore_best_weights=True, verbose=1
    ),
    tf.keras.callbacks.ModelCheckpoint(
        "/content/resnet50v2_warmup_best.keras", monitor="val_accuracy",
        mode="max", save_best_only=True, verbose=1
    ),
]

print("\n🚀 Warm-up (backbone FROZEN)...")
hist_w = model.fit(
    train_ds,
    validation_data=val_ds,
    epochs=10,
    callbacks=warmup_cbs,
    class_weight=CLASS_WEIGHTS,
    verbose=1
)

# --------------------------------------------------------------------------------
# 3) Fine-tune: unfreeze last ~25% of layers, BUT keep BatchNorm NON-trainable
#    This avoids BN stat drift that caused your exploding val_loss.
# --------------------------------------------------------------------------------
def set_finetune_layers(base, unfreeze_ratio=0.25):
    # Keep all BN layers frozen
    for layer in base.layers:
        if isinstance(layer, L.BatchNormalization):
            layer.trainable = False
        else:
            layer.trainable = False  # default; we’ll unfreeze tail below

    # Unfreeze the last N non-BN layers (by index)
    layers = [ly for ly in base.layers if not isinstance(ly, L.BatchNormalization)]
    n_unfreeze = max(1, int(len(layers) * unfreeze_ratio))
    for ly in layers[-n_unfreeze:]:
        ly.trainable = True

set_finetune_layers(base_model, unfreeze_ratio=0.28)

# Recompile with smaller LR for FT
model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=3e-4),
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

finetune_cbs = [
    tf.keras.callbacks.ReduceLROnPlateau(
        monitor="val_loss", factor=0.5, patience=2, min_lr=1e-6, verbose=1
    ),
    tf.keras.callbacks.EarlyStopping(
        monitor="val_accuracy", mode="max", patience=6, restore_best_weights=True, verbose=1
    ),
    tf.keras.callbacks.ModelCheckpoint(
        "/content/resnet50v2_finetune_best.keras", monitor="val_accuracy",
        mode="max", save_best_only=True, verbose=1
    ),
]

print("\n🔧 Fine-tuning (tail UNFROZEN, BN FROZEN)...")
hist_ft = model.fit(
    train_ds,
    validation_data=val_ds,
    epochs=20,
    callbacks=finetune_cbs,
    class_weight=CLASS_WEIGHTS,
    verbose=1
)

