def find_split_root(start_dir: Path):
    """
    Walk start_dir to locate a directory that directly contains
    train/ (and validation|val/) and test/ folders.
    Returns the Path to that directory, or None if not found.
    """
    # Search up to a few levels deep
    max_depth = 4
    start_depth = len(start_dir.resolve().parts)

    for root, dirs, _ in os.walk(start_dir):
        root_path = Path(root)
        depth = len(root_path.resolve().parts) - start_depth
        if depth > max_depth:
            continue

        dirset = set([d.lower() for d in dirs])
        # Accept 'validation' or 'val' as the validation split
        has_train = "train" in dirset
        has_val   = ("validation" in dirset) or ("val" in dirset)
        has_test  = "test" in dirset

        if has_train and has_val and has_test:
            return root_path

    return None

