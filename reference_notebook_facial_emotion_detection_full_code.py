def train_one_epoch(model, loader, criterion, optimizer, scaler=None):
    model.train()
    running_loss = 0.0
    correct = 0
    total = 0

    for images, labels in loader:
        images = images.to(device, non_blocking=True)
        labels = labels.to(device, non_blocking=True)

        optimizer.zero_grad(set_to_none=True)

        if scaler is not None:
            with torch.cuda.amp.autocast():
                outputs = model(images)
                loss = criterion(outputs, labels)
            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()
        else:
            outputs = model(images)
            loss = criterion(outputs, labels)
            loss.backward()
            optimizer.step()

        running_loss += loss.item() * images.size(0)
        preds = outputs.argmax(1)
        correct += (preds == labels).sum().item()
        total += labels.size(0)

    epoch_loss = running_loss / max(total, 1)
    epoch_acc = correct / max(total, 1)
    return epoch_loss, epoch_acc

@torch.no_grad()
def evaluate(model, loader, criterion):
    model.eval()
    running_loss = 0.0
    all_labels = []
    all_preds  = []

    for images, labels in loader:
        images = images.to(device, non_blocking=True)
        labels = labels.to(device, non_blocking=True)

        outputs = model(images)
        loss = criterion(outputs, labels)

        running_loss += loss.item() * images.size(0)
        preds = outputs.argmax(1)

        all_labels.append(labels.cpu().numpy())
        all_preds.append(preds.cpu().numpy())

    all_labels = np.concatenate(all_labels) if all_labels else np.array([])
    all_preds  = np.concatenate(all_preds)  if all_preds  else np.array([])

    epoch_loss = running_loss / max(len(all_labels), 1)
    acc = accuracy_score(all_labels, all_preds) if len(all_labels) else 0.0
    macro_f1 = f1_score(all_labels, all_preds, average='macro', zero_division=0) if len(all_labels) else 0.0
    pr, rc, f1, _ = precision_recall_fscore_support(all_labels, all_preds, average=None, zero_division=0)

    return {
        "loss": epoch_loss,
        "acc":  acc,
        "macro_f1": macro_f1,
        "per_class": {
            "precision": pr,
            "recall": rc,
            "f1": f1
        },
        "y_true": all_labels,
        "y_pred": all_preds,
        "cm": confusion_matrix(all_labels, all_preds, labels=list(range(NUM_CLASSES))) if len(all_labels) else None
    }

