def run_experiment(color_mode="rgb", epochs=3, lr=3e-4, wd=1e-4) -> Dict:
    loaders, class_to_idx = build_loaders(color_mode)
    idx_to_class = {v: k for k, v in class_to_idx.items()}
    assert [idx_to_class[i] for i in range(NUM_CLASSES)] == CLASS_NAMES, \
        f"Class order mismatch: got {idx_to_class}"

    model = build_model(NUM_CLASSES).to(device)
    criterion = nn.CrossEntropyLoss()
    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=wd)
    scaler = torch.cuda.amp.GradScaler() if device.type == "cuda" else None

    best_state = None
    best_val_acc = -1
    history = {"train_loss": [], "train_acc": [], "val_loss": [], "val_acc": []}

    start = time.time()
    for epoch in range(1, epochs + 1):
        tr_loss, tr_acc = train_one_epoch(model, loaders["train"], criterion, optimizer, scaler=scaler)
        val_metrics = evaluate(model, loaders["val"], criterion)

        history["train_loss"].append(tr_loss)
        history["train_acc"].append(tr_acc)
        history["val_loss"].append(val_metrics["loss"])
        history["val_acc"].append(val_metrics["acc"])

        if val_metrics["acc"] > best_val_acc:
            best_val_acc = val_metrics["acc"]
            best_state = copy.deepcopy(model.state_dict())

        print(f"[{color_mode}] Epoch {epoch}/{epochs} "
              f"| train_loss={tr_loss:.4f} acc={tr_acc:.4f} "
              f"| val_loss={val_metrics['loss']:.4f} acc={val_metrics['acc']:.4f}")

    elapsed = time.time() - start

    # Load best and test
    if best_state is not None:
        model.load_state_dict(best_state)

    val_metrics  = evaluate(model, loaders["val"],  criterion)
    test_metrics = evaluate(model, loaders["test"], criterion)

    results = {
        "color_mode": color_mode,
        "history": history,
        "val": val_metrics,
        "test": test_metrics,
        "time_sec": elapsed,
    }
    return results

