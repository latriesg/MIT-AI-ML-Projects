print("\nClassification Report\n---------------------")
print(classification_report(y_true, y_pred, target_names=class_names, digits=4))

cm = confusion_matrix(y_true, y_pred)
print("Confusion Matrix:\n", cm)

# Choose "Parasitized" as positive class (fallback to index 1 if not present)
pos_idx = class_names.index("Parasitized") if "Parasitized" in class_names else 1
roc = roc_auc_score((y_true == pos_idx).astype(int), y_prob[:, pos_idx])
pr  = average_precision_score((y_true == pos_idx).astype(int), y_prob[:, pos_idx])
print(f"ROC-AUC: {roc:.4f} | PR-AUC: {pr:.4f}")

# Plot CM
def plot_cm(cm, labels):
    fig = plt.figure(figsize=(4.5,4.5))
    plt.imshow(cm, interpolation='nearest')
    plt.title('Confusion Matrix')
    ticks = np.arange(len(labels))
    plt.xticks(ticks, labels, rotation=45, ha='right'); plt.yticks(ticks, labels)
    thresh = cm.max()/2.0
    for i in range(cm.shape[0]):
        for j in range(cm.shape[1]):
            plt.text(j, i, cm[i,j], ha="center", va="center",
                     color="white" if cm[i,j] > thresh else "black")
    plt.ylabel('True'); plt.xlabel('Predicted'); plt.tight_layout()
    return fig

fig = plot_cm(cm, class_names)
plt.show()

