# Use the same path you set above; you pointed to TRAIN explicitly:
DATASET_ROOT = Path(dataset_path)  # e.g., .../cell_images/train
assert DATASET_ROOT.exists(), f"Not found: {DATASET_ROOT}"

img_size = (224, 224)
batch_size = 32
seed = 42

# --- DEBUG: show what's under your path so we see real names/case ---
print("Listing immediate subfolders under:", DATASET_ROOT)
for p in sorted([x for x in DATASET_ROOT.iterdir() if x.is_dir()]):
    print("  -", p.name)

TARGETS = {"parasitized", "uninfected"}

def has_class_folders(p: Path) -> bool:
    """Case-insensitive check for the two class folders."""
    subdirs = {d.name.strip().lower() for d in p.iterdir() if d.is_dir()}
    return TARGETS.issubset(subdirs)

def find_val_sibling(train_dir: Path) -> Path | None:
    """Prefer 'val' then 'test' as validation sibling of a train/ directory."""
    for name in ("val", "validation", "test"):
        cand = train_dir.parent / name
        if cand.is_dir() and has_class_folders(cand):
            return cand
    return None

def make_ds(directory: Path, shuffle: bool) -> tf.data.Dataset:
    return tf.keras.utils.image_dataset_from_directory(
        directory,
        image_size=img_size,
        batch_size=batch_size,
        shuffle=shuffle,
        seed=seed if shuffle else None,
    )

def detect_and_build(root: Path):
    """
    Returns: (train_ds, val_ds, class_names)

    Handles:
      1) root is the TRUE root: root/Parasitized, root/Uninfected  -> uses validation_split
      2) root is the TRUE root: root/train/... and root/(val|test)/... -> uses explicit dirs
      3) root IS the train/ directory -> auto-find sibling val/ or test/
    """
    # 3) If user set root to ".../train", treat it as the train dir
    if root.name.lower() == "train" and has_class_folders(root):
        val_dir = find_val_sibling(root)
        if val_dir is None:
            raise RuntimeError(
                f"Found train dir at {root}, but no matching 'val'/'validation'/'test' sibling with class folders."
            )
        train_ds = make_ds(root, shuffle=True)
        val_ds   = make_ds(val_dir, shuffle=False)
        return train_ds, val_ds, train_ds.class_names

    # 1) Single-root with class folders
    if has_class_folders(root):
        train_ds = tf.keras.utils.image_dataset_from_directory(
            root, validation_split=0.2, subset="training", seed=seed,
            image_size=img_size, batch_size=batch_size
        )
        val_ds = tf.keras.utils.image_dataset_from_directory(
            root, validation_split=0.2, subset="validation", seed=seed,
            image_size=img_size, batch_size=batch_size
        )
        return train_ds, val_ds, train_ds.class_names

    # 2) Pre-split under a parent root
    tdir = root / "train"
    vdir = root / "val"
    xdir = root / "test"   # accept test as validation if no val/
    if tdir.is_dir() and has_class_folders(tdir):
        if vdir.is_dir() and has_class_folders(vdir):
            train_ds = make_ds(tdir, shuffle=True)
            val_ds   = make_ds(vdir, shuffle=False)
            return train_ds, val_ds, train_ds.class_names
        if xdir.is_dir() and has_class_folders(xdir):
            train_ds = make_ds(tdir, shuffle=True)
            val_ds   = make_ds(xdir, shuffle=False)
            return train_ds, val_ds, train_ds.class_names

    # If we get here, structure is unknown
    raise RuntimeError(
        f"Could not detect a valid structure under {root}.\n"
        "Expected either:\n"
        "  A) root/Parasitized and root/Uninfected, OR\n"
        "  B) root/train/(Parasitized,Uninfected) and root/(val or test)/(Parasitized,Uninfected), OR\n"
        "  C) you passed the train/ directory directly (which must contain Parasitized/ and Uninfected/), with a sibling val/ or test/."
    )

# Build datasets
train_ds, val_ds, class_names = detect_and_build(DATASET_ROOT)

# Guard: if 'train'/'test' appear as class names, it's the wrong level
if set(name.lower() for name in class_names) & {"train", "test", "val", "validation"}:
    raise RuntimeError(
        f"Bad class names detected: {class_names}. "
        "Fix the path so the IMMEDIATE subfolders are Parasitized/ and Uninfected/, "
        "or point to the parent that contains train/ and val/test/ each with those class folders."
    )

print("Classes:", class_names)

# Prefetch for performance
AUTOTUNE = tf.data.AUTOTUNE
train_ds = train_ds.cache().shuffle(1000).prefetch(AUTOTUNE)
val_ds   = val_ds.cache().prefetch(AUTOTUNE)

# Model with transfer learning (MobileNetV2)
base_model = keras.applications.MobileNetV2(
    input_shape=img_size + (3,),
    include_top=False,
    weights="imagenet"
)
base_model.trainable = False

inputs = keras.Input(shape=img_size + (3,))
x = layers.Rescaling(1./255)(inputs)
x = layers.RandomFlip("horizontal")(x)
x = layers.RandomRotation(0.05)(x)
x = layers.RandomZoom(0.1)(x)
x = layers.RandomContrast(0.1)(x)
x = base_model(x, training=False)
x = layers.GlobalAveragePooling2D()(x)
x = layers.Dropout(0.25)(x)
outputs = layers.Dense(len(class_names), activation="softmax")(x)
model = keras.Model(inputs, outputs)

model.compile(
    optimizer=keras.optimizers.Adam(1e-4),
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

history = model.fit(train_ds, validation_data=val_ds, epochs=5, verbose=1)


# =========================================
# 5) Evaluation: classification report, CM, ROC-AUC, PR-AUC
