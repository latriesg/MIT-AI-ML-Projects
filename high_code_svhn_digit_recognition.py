# --- Helper to load and return train/test ready for CNN ---
def load_svhn_for_cnn(h5_path, test_size=None, seed=42):

    with h5py.File(h5_path, "r") as f:
        keys = set(f.keys())
        # Case 1: File already split
        if {"X_train","y_train","X_test","y_test"}.issubset(keys):
            X_train = np.array(f["X_train"])
            y_train = np.array(f["y_train"])
            X_test  = np.array(f["X_test"])
            y_test  = np.array(f["y_test"])
            # If validation exists, merge it into training pool (we'll use validation_split at fit time)
            if {"X_val","y_val"}.issubset(keys):
                X_val = np.array(f["X_val"])
                y_val = np.array(f["y_val"])
                X_train = np.concatenate([X_train, X_val], axis=0)
                y_train = np.concatenate([y_train, y_val], axis=0)
        # Case 2: Only X/y exist → do our own train/test split
        elif {"X","y"}.issubset(keys):
            X = np.array(f["X"])
            y = np.array(f["y"])
            if test_size is None:
                test_size = 0.2
            X_train, X_test, y_train, y_test = train_test_split(
                X, y, test_size=test_size, random_state=seed, stratify=y
            )
        else:
            raise ValueError(f"Unexpected keys in file: {list(keys)}")

    # Ensure labels are 0–9 (classic SVHN sometimes uses 10 to denote '0')
    y_train = (y_train % 10).astype("int64")
    y_test  = (y_test  % 10).astype("int64")

    # Normalize to [0,1]
    X_train = X_train.astype("float32") / 255.0
    X_test  = X_test.astype("float32") / 255.0

    # Add channel dimension for CNN if missing → (N, 32, 32, 1)
    if X_train.ndim == 3:
        X_train = np.expand_dims(X_train, axis=-1)
    if X_test.ndim == 3:
        X_test = np.expand_dims(X_test, axis=-1)

    # Sanity checks
    assert X_train.shape[1:3] == (32, 32), f"Expected 32x32 images, got {X_train.shape[1:3]}"
    assert X_test.shape[1:3] == (32, 32), f"Expected 32x32 images, got {X_test.shape[1:3]}"
    assert X_train.shape[-1] in (1, 3), "Expected grayscale or RGB channels."

    return X_train, y_train, X_test, y_test

